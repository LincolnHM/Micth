-- Se puede correr más de una vez (usa IF NOT EXISTS / DROP POLICY IF EXISTS).
--
-- Qué hace: crea la tabla `cotizador_proveedor`, donde el panel guarda los
-- perfumes del catálogo del proveedor con su precio en dólares. El panel
-- (Herramientas → Cotizador) calcula con eso el costo puesto en Perú y tu
-- precio de venta.
--
-- Es SOLO para el admin: los clientes de la tienda no pueden leerla (así nadie
-- ve a quién le compras ni a cuánto). Sin correr este archivo el cotizador
-- igual funciona, pero la lista se guarda solo en el navegador donde la cargues.

CREATE TABLE IF NOT EXISTS cotizador_proveedor (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor    text        NOT NULL DEFAULT 'zimaxx',
  nombre       text        NOT NULL,
  marca        text,
  presentacion text,                          -- ej. "100 ml"
  precio_usd   numeric(10,2) NOT NULL CHECK (precio_usd >= 0),
  imagen       text,
  actualizado  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cotizador_proveedor_proveedor_idx ON cotizador_proveedor (proveedor);

ALTER TABLE cotizador_proveedor ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "admin_cotizador" ON cotizador_proveedor;
CREATE POLICY "admin_cotizador" ON cotizador_proveedor FOR ALL TO authenticated
  USING      ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- ─── Comprobación: debe salir UNA fila, la política admin_cotizador ──────────
SELECT tablename, policyname, cmd, roles
FROM pg_policies
WHERE tablename = 'cotizador_proveedor';
